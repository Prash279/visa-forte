// Hashes crs-rules.json and writes an 8-character fingerprint to
// src/lib/crs-rules.version.ts. Run automatically before every build,
// dev server start, and test run via package.json lifecycle hooks.
// The output file is gitignored — never edit it by hand.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const rulesPath = resolve(__dirname, '../src/lib/crs-rules.json')
const outPath   = resolve(__dirname, '../src/lib/crs-rules.version.ts')

// Normalize CRLF to LF before hashing: git materializes the JSON with CRLF on
// Windows and LF on Linux CI, and the fingerprint must track rule content,
// not the platform's line endings.
const hash = createHash('sha256')
  .update(readFileSync(rulesPath, 'utf8').replace(/\r\n/g, '\n'))
  .digest('hex')
  .slice(0, 8)

writeFileSync(
  outPath,
  [
    '// Auto-generated by scripts/hash-crs-rules.mjs — do not edit.',
    '// Re-generated before every build, dev start, and test run.',
    `export const CRS_RULES_VERSION = '${hash}' as const`,
    '',
  ].join('\n')
)

console.log(`[crs-rules] hash: ${hash}`)